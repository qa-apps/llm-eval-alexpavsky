def query_rag(question: str) -> str:
    """Call the production RAG API and return the answer string."""
    try:
        r = requests.post(
            f"{RAG_API}/api/rag/query",
            json={"query": question},
            timeout=60,
        )
        r.raise_for_status()
        return r.json().get("answer", "")
    except Exception as e:
        log(f"    RAG call failed: {e}")
        return ""


class PermissiveCorrectnessMetric:
    """Giskard-compatible correctness metric with a stable JSON contract."""

    name = "correctness"

    def __init__(self, provider: dict[str, str]) -> None:
        self.provider = provider

    def __call__(self, question_sample, answer) -> dict:
        response = requests.post(
            f"{self.provider['base_url']}/chat/completions",
            headers=judge_headers(
                self.provider["model"], self.provider["api_key"]
            ),
            json={
                "model": self.provider["model"],
                "temperature": 0,
                "max_tokens": int(os.environ.get("JUDGE_MAX_TOKENS", "2048")),
                "response_format": {"type": "json_object"},
                "messages": [
                    {
                        "role": "system",
                        "content": (
                            "Evaluate whether a chatbot answer is basically useful, relevant, and "
                            "plausible. The reference is one acceptable example, not an exhaustive "
                            "checklist, so the answer may give different valid facts or examples. "
                            "Be permissive about wording, tone, brevity, omitted details, and mild "
                            "irrelevance. Mark false only when the answer is empty, clearly fails "
                            "to answer the question, contradicts established facts, or contains "
                            "obviously fabricated material facts. Return exactly one JSON object "
                            "with boolean correctness and string correctness_reason."
                        ),
                    },
                    {
                        "role": "user",
                        "content": (
                            f"Question: {question_sample.question}\n\n"
                            f"Reference answer: {question_sample.reference_answer}\n\n"
                            f"Chatbot answer: {answer.message}"
                        ),
                    },
                ],
            },
            timeout=int(os.environ.get("JUDGE_TIMEOUT_SEC", "120")),
        )
        response.raise_for_status()
        payload = response.json()
        content = (payload["choices"][0]["message"].get("content") or "").strip()
        if not content:
            usage = payload.get("usage", {})
            raise ValueError(
                "Judge returned empty content "
                f"(completion_tokens={usage.get('completion_tokens', 'unknown')})"
            )
        content = re.sub(r"^```(?:json)?\s*|\s*```$", "", content, flags=re.IGNORECASE)
        result = json.loads(content)

        correctness = result.get("correctness")
        if isinstance(correctness, str):
            normalized = correctness.strip().lower()
            if normalized in {"true", "yes", "pass", "correct"}:
                correctness = True
            elif normalized in {"false", "no", "fail", "incorrect"}:
                correctness = False
        if not isinstance(correctness, bool):
            raise ValueError(f"Judge omitted boolean correctness: {result}")

        return {
            "correctness": correctness,
            "correctness_reason": str(result.get("correctness_reason", "No reason supplied.")),
        }


def extract_cases(report) -> list[dict]:
    """One dict per generated question: prompt, answers, PASS/FAIL, reason."""
    try:
        df = report.to_pandas()
    except Exception as e:
        log(f"  WARN: could not read per-question results: {e}")
        return []
    import pandas as pd

    cases = []
    for i, (idx, row) in enumerate(df.iterrows(), start=1):
        metadata = row.get("metadata") if isinstance(row.get("metadata"), dict) else {}
        correctness = row.get("correctness")
        passed = None if correctness is None or pd.isna(correctness) else bool(correctness)
        cases.append({
            "id": f"giskard-{i}",
            "giskard_id": str(row.get("id", idx)),
            "question_type": str(metadata.get("question_type", "generated")),
            "topic": str(metadata.get("topic", "")),
            "prompt": str(row.get("question", "")),
            "reference_answer": str(row.get("reference_answer", "")),
            "answer": str(row.get("agent_answer", "")),
            "passed": passed,
            "status": "PASS" if passed else ("FAIL" if passed is False else "N/A"),
            "reason": str(row.get("correctness_reason", "") or ""),
        })
    return cases


def main() -> None:
    log("=" * 72)
    log("Giskard RAG Evaluation")
    log("=" * 72)
    log(f"  RAG_API:       {RAG_API}")
    log(f"  num_questions: {NUM_QUESTIONS}")
    log("")

    # Lazy imports so a missing dep gives a clear error.
    try:
        import pandas as pd
        from giskard.rag import generate_testset, evaluate, KnowledgeBase
        from giskard.rag.metrics.correctness import CorrectnessMetric
    except ImportError as e:
        fail(f"Missing dependency: {e}. Run: pip install -r eval/requirements.txt")

    # Use the same cloud judge as Ragas — Giskard needs an OpenAI-compatible
    # client for both question generation and answer evaluation.
    from rotating_llm import build_provider_list
    providers = build_provider_list()
    if not providers:
        fail("Cloud judge is not configured. Set DEEPSEEK_API_KEY or TOGETHER_API_KEY.")

    from rotating_llm import configure_giskard
    primary_label = configure_giskard(providers, log)

    log("")
    log("Step 1/3: Building knowledge base...")
    df = pd.DataFrame({"text": KB_CHUNKS})
    knowledge_base = KnowledgeBase(df)
    log(f"  KB chunks: {len(df)}")

    log("")
    log(f"Step 2/3: Auto-generating {NUM_QUESTIONS} questions...")
    t0 = time.time()
    try:
        testset = generate_testset(
            knowledge_base,
            num_questions=NUM_QUESTIONS,
            language="en",
            agent_description=(
                "QA assistant for alexpavsky.com — answers questions about "
                "Playwright, LLM evaluation, RAG testing, MCP, agentic testing, "
                "cloud QA, and the FinNova case study."
            ),
        )
    except Exception as e:
        fail(f"Test generation failed: {e}")
    log(f"  Generated {len(testset)} questions in {time.time()-t0:.1f}s")

    log("")
    log("Step 3/3: Running RAG against generated questions + evaluating...")

    def rag_callable(question: str, history=None):
        return query_rag(question)

    t0 = time.time()
    try:
        class LocalCorrectnessMetric(PermissiveCorrectnessMetric, CorrectnessMetric):
            pass

        report = evaluate(
            rag_callable,
            testset=testset,
            knowledge_base=knowledge_base,
            metrics=[LocalCorrectnessMetric(providers[0])],
        )
    except Exception as e:
        fail(f"Evaluation failed: {e}")
    log(f"  Done in {time.time()-t0:.1f}s")

    # Persist report.
    html_path = RESULTS_DIR / "giskard_rag.html"
    json_path = RESULTS_DIR / "giskard_rag.json"
    try:
        report.to_html(str(html_path))
        log(f"  HTML report: {html_path}")
    except Exception as e:
        log(f"  WARN: could not write HTML: {e}")

    cases = extract_cases(report)
    passed = sum(1 for c in cases if c["passed"] is True)
    summary = {
        "rag_api": RAG_API,
        "num_questions": NUM_QUESTIONS,
        "judge": primary_label,
        "correctness": None,
        "minimum_correctness": MIN_CORRECTNESS,
        "passed": passed,
        "failed": sum(1 for c in cases if c["passed"] is False),
        "total": len(cases),
    }
    try:
        # Giskard's report exposes a correctness metric on the full set.
        correctness = float(report.correctness) if hasattr(report, "correctness") else None
        summary["correctness"] = correctness
    except Exception:
        pass
    if summary["correctness"] is None and cases:
        summary["correctness"] = passed / len(cases)
    summary["evaluation_completed"] = (
        summary["correctness"] is not None and len(cases) == NUM_QUESTIONS
    )
    summary["quality_passed"] = (
        summary["correctness"] >= MIN_CORRECTNESS
        if summary["evaluation_completed"]
        else None
    )

    json_path.write_text(json.dumps(summary, indent=2))
    log(f"  JSON summary: {json_path}")

    cases_path = RESULTS_DIR / "giskard_rag_cases.json"
    cases_path.write_text(
        json.dumps({**summary, "cases": cases}, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    log(f"  Per-question results: {cases_path}")
    for c in cases:
        log(f"    [{c['status']}] {c['id']} ({c['question_type']}): {c['prompt'][:90]}")

    log("")
    log("=" * 72)
    log("Giskard RAG eval complete.")
    log(f"  Correctness: {summary['correctness']}")
    log(f"  Minimum:     {MIN_CORRECTNESS}")
    log("=" * 72)

    if summary["correctness"] is None:
        fail("Giskard did not return a correctness score.")
    if summary["correctness"] < MIN_CORRECTNESS:
        fail(
            f"Correctness {summary['correctness']:.3f} is below "
            f"{MIN_CORRECTNESS:.3f}; inspect the saved report for obvious hallucinations."
        )


if __name__ == "__main__":
    main()
