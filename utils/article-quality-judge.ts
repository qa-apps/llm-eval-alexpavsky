/**
 * article-quality-judge.ts
 *
 * LLM-as-a-judge for "is this real meaningful article content, or is it
 * an error / empty / fallback / nonsense blob?". Used by the
 * contentQuality spec to catch the failure mode the user reported
 * repeatedly: the modal opens but the body is junk — 3 random words,
 * an "offline" notice, a Datawrapper "content blocked" page, or a
 * one-line fallback message. Functional tests don't catch this because
 * the modal is technically "loaded" and has "some" text.
 *
 * Provider selection reuses the existing model-registry rotation
 * (Groq → others) from utils/llm-judges.ts.
 */

import { request } from '@playwright/test';
import { resolveAllProviders, getProviderSummary } from './model-registry';
import { recordJudgeVerdict } from './verdict-reporter';

export interface ArticleQualityVerdict {
  isReal: boolean;
  score: 1 | 2 | 3 | 4 | 5;
  reasoning: string;
  judgeUsed: string; // "providerName:model" of the judge that ran, or "" on failure
}

const BODY_SYSTEM_PROMPT = `You are a content-quality classifier. You receive raw text extracted from an article modal on a news/blog site. Decide whether the text contains a real, meaningful article body OR whether it is some failure state.

Score on this exact scale:
- 5 = substantive article body, multiple coherent paragraphs on a clear topic
- 4 = short but legitimate article (intro + 1-2 paragraphs)
- 3 = mostly real content but truncated / partial / mostly the header
- 2 = error message, fallback notice, "preview unavailable", "loading...", offline
- 1 = empty, gibberish, random unrelated words, single header with no body

Treat scores 4-5 as PASS (isReal=true). Treat 1-3 as FAIL (isReal=false).

The user wants tests to catch the 1-3 cases. Be strict. A title plus one boilerplate sentence is NOT acceptable. Real article = informative paragraphs about a topic.

Respond ONLY with strict JSON, no markdown:
{"score": 1-5, "isReal": true/false, "reasoning": "1-2 sentences explaining the classification"}`;

const HEADLINE_SYSTEM_PROMPT = `You are a headline-quality classifier. You receive ONLY a news headline and its source label (no article body — the user would have to click through to read more). Decide whether the headline looks like a real article headline that a recruiter or reader would respect, OR whether it is junk / placeholder / error / nonsense generated by a broken site.

Score on this exact scale:
- 5 = clear, specific, real-sounding article headline on an identifiable topic
- 4 = legitimate headline, including a short topic label or question-form title
- 3 = suspiciously malformed or template-like, but not conclusive
- 2 = looks like SITE infrastructure failure: placeholder copy from a missing template, "Loading...", a fallback notice, or "Untitled"
- 1 = empty, gibberish, random unrelated words, debug strings, or obviously broken

Treat 4-5 as PASS (isReal=true). Treat 1-3 as FAIL (isReal=false).

CRITICAL distinction:
- A headline that MENTIONS an error topic ("Error: Cannot Set Headers After They Are Sent", "Fixing memory leaks in Python", "How to debug 502 Bad Gateway", "Cannot read property of undefined explained", "Common SQL errors and fixes") is a LEGITIMATE technical article — pass (4-5). Developers write articles ABOUT errors all the time.
- Only flag (1-3) when the text itself looks broken: literal "Loading...", "Untitled", empty string, "[object Object]", lorem ipsum, malformed template output, or content with no recognisable meaning.
- "React Props" is a valid short technical article title. A question such as "Can you spot the AI's mistake?" is a valid headline. Do not demand a verb, detailed angle, or full article summary from a headline.

Do NOT penalise the headline for:
  - being short (expected — it's a headline)
  - lacking a body (expected — headlines don't have bodies)
  - being about an error/exception/bug topic (legit dev content)
  - missing punctuation or being all-lowercase

Respond ONLY with strict JSON, no markdown:
{"score": 1-5, "isReal": true/false, "reasoning": "1-2 sentences explaining the classification"}`;

const PASSING = 4;

export type JudgeMode = 'body' | 'headline';

function clip(s: string, n: number): string {
  return s.length > n ? s.slice(0, n) + ' …[truncated]' : s;
}

/**
 * Run the content-quality judge. If no providers are reachable, returns
 * a fail with reasoning. Never throws.
 *
 * mode='body' (default): judges full article body; expects multi-paragraph
 *   real content (used for Live Feed modal reader).
 * mode='headline': judges a headline + source only; tolerates short content
 *   as long as it looks like a real headline (used for LIVE rail items
 *   where only the title is visible without click-through).
 */
export async function runArticleQualityJudge(
  articleTitle: string,
  articleSource: string,
  articleBodyText: string,
  mode: JudgeMode = 'body',
): Promise<ArticleQualityVerdict> {
  const verdict = await judgeArticle(articleTitle, articleSource, articleBodyText, mode);
  recordJudgeVerdict({
    judgeName: `articleQuality:${mode}`,
    judge: mode === 'headline' ? 'Headline Quality' : 'Article Body Quality',
    judgeModel: verdict.judgeUsed,
    criteria: [
      mode === 'headline'
        ? 'Looks like a real, specific article headline (not a placeholder, error or gibberish).'
        : 'Contains a real, meaningful article body (not an error, fallback notice or junk).',
      `Scores ${PASSING}-5 pass; 1-${PASSING - 1} fail.`,
    ],
    score: verdict.score,
    maxScore: 5,
    passingScore: PASSING,
    passed: verdict.isReal,
    prompt: mode === 'headline'
      ? `Headline: ${articleTitle}\nSource: ${articleSource}`
      : `Title: ${articleTitle}\nSource: ${articleSource}\n\n${clip(articleBodyText, 4000)}`,
    response: mode === 'headline' ? articleTitle : clip(articleBodyText, 4000),
    reasoning: verdict.reasoning,
  });
  return verdict;
}

async function judgeArticle(
  articleTitle: string,
  articleSource: string,
  articleBodyText: string,
  mode: JudgeMode,
): Promise<ArticleQualityVerdict> {
  const providers = await resolveAllProviders('M');
  if (providers.length === 0) {
    const summary = await getProviderSummary();
    return {
      isReal: false,
      score: 1,
      reasoning: `No usable judge provider — cannot evaluate. ${summary}`,
      judgeUsed: '',
    };
  }

  const systemPrompt = mode === 'headline' ? HEADLINE_SYSTEM_PROMPT : BODY_SYSTEM_PROMPT;
  const userPayload = mode === 'headline'
    ? [
        `HEADLINE: ${clip(articleTitle, 200)}`,
        `SOURCE LABEL: ${clip(articleSource, 80)}`,
        '',
        'Classify whether this looks like a real article headline or junk/placeholder/error. Reply JSON only.',
      ].join('\n')
    : [
        `ARTICLE TITLE: ${clip(articleTitle, 200)}`,
        `SOURCE LABEL: ${clip(articleSource, 80)}`,
        `RAW MODAL BODY TEXT (everything user can see inside the modal):`,
        '---BEGIN---',
        clip(articleBodyText, 6000),
        '---END---',
        '',
        'Classify per the scale. Reply JSON only.',
      ].join('\n');

  let lastReason = '';
  for (const { baseUrl, model, headers, providerName } of providers) {
    const tag = `${providerName}:${model}`;
    console.log(`[article-quality-judge] via ${tag} — title="${clip(articleTitle, 60)}"`);
    const priorityDeadline = Date.now() + Number(process.env.LOCAL_LLM_PRIORITY_MAX_WAIT_SEC || 0) * 1000;
    while (true) {
      const reqContext = await request.newContext();
      try {
        const resp = await reqContext.post(baseUrl, {
          headers,
          timeout: Number(process.env.LOCAL_LLM_TIMEOUT_MS || 180_000),
          data: {
            model,
            messages: [
              { role: 'system', content: systemPrompt },
              { role: 'user', content: userPayload },
            ],
            temperature: 0,
            response_format: { type: 'json_object' },
            max_tokens: Number(process.env.LOCAL_LLM_MAX_TOKENS || 1024),
          },
        });
        const text = await resp.text();
        if (!resp.ok()) {
          if (resp.status() === 503 && Date.now() < priorityDeadline) {
            console.log(`[article-quality-judge] interactive work owns GPU; retrying ${tag} in 5s`);
            await new Promise((resolve) => setTimeout(resolve, Math.min(5000, priorityDeadline - Date.now())));
            continue;
          }
          lastReason = `${tag} HTTP ${resp.status()}: ${clip(text, 200)}`;
          break;
        }
        const json = JSON.parse(text);
        const content = json?.choices?.[0]?.message?.content;
        if (typeof content !== 'string') {
          lastReason = `${tag} no message.content in response`;
          break;
        }
        const parsed = JSON.parse(content);
        const rawScore = Number(parsed.score);
        const score = (Number.isFinite(rawScore) ? Math.max(1, Math.min(5, Math.round(rawScore))) : 1) as 1 | 2 | 3 | 4 | 5;
        const isReal = typeof parsed.isReal === 'boolean' ? parsed.isReal : score >= PASSING;
        return {
          score,
          isReal,
          reasoning: typeof parsed.reasoning === 'string' ? parsed.reasoning.slice(0, 500) : 'No reasoning provided.',
          judgeUsed: tag,
        };
      } catch (e) {
        if (Date.now() < priorityDeadline) {
          console.log(`[article-quality-judge] model was preempted; retrying ${tag} in 5s`);
          await new Promise((resolve) => setTimeout(resolve, Math.min(5000, priorityDeadline - Date.now())));
          continue;
        }
        lastReason = `${tag} threw ${String(e).slice(0, 200)}`;
        break;
      } finally {
        await reqContext.dispose();
      }
    }
  }

  return {
    isReal: false,
    score: 1,
    reasoning: `All judge providers failed. Last: ${lastReason}`,
    judgeUsed: '',
  };
}
